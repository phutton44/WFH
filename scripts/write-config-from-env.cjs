"use strict";

/**
 * Writes root `config.js` for optional split-origin dev (see README).
 * Always succeeds — empty `apiBase` means same-origin `/api/*` (normal Vercel deploy).
 */
const fs = require("fs");
const path = require("path");

function loadDotEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const text = fs.readFileSync(filePath, "utf8");
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) {
      continue;
    }
    const eq = t.indexOf("=");
    if (eq === -1) {
      continue;
    }
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = val;
    }
  }
}

const root = path.join(__dirname, "..");
loadDotEnvFile(path.join(root, ".env.local"));
loadDotEnvFile(path.join(root, ".env"));

const apiBase = (process.env.WFH_PUBLIC_API_BASE || "").trim().replace(/\/$/, "");

const contents = `/** Generated by \`npm run build\`. Optional: set WFH_PUBLIC_API_BASE in Vercel or .env.local. */
window.WFH_API = ${JSON.stringify({ apiBase })};
`;

fs.writeFileSync(path.join(root, "config.js"), contents, "utf8");
console.log("Wrote config.js (WFH_API).");
